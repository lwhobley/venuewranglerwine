    },
    AppRole.auditor: {
      Permission.orgRead,
      Permission.venueRead,
      Permission.membershipRead,
      Permission.auditRead,
      Permission.wineCatalogRead,
      Permission.wineCostRead,
      Permission.reservationRead,
      Permission.floorRead,
      Permission.guestRead,
      Permission.scheduleRead,
      Permission.documentRead,
      Permission.eventRead,
      Permission.salesRead,
      Permission.reportOperational,
      Permission.reportFinancial,
    },
  };

  static Set<String> permissionsFor(AppRole role) {
    return Set.unmodifiable(grants[role] ?? const {});
  }

  static bool roleHas(AppRole role, String permission) {
    return grants[role]?.contains(permission) ?? false;
  }
